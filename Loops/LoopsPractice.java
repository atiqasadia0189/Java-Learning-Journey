public class LoopsPractice{
 public static void main(String[] args){
   // For Loop
   for(int i = 0; i <= 100; i++){
   System.out.println(i);
   }
   // While Loop
   int j = 0;
   while(j <= 100){
   System.out.println(j);
   j++;
   }
   // do-while Loop
   int k = 0;
   do {
     System.out.println(k);
     k++;
   } while(k <= 100);
}
}
